#this is type conversion
variable_1 = "100"
var2 = 10.220
var3 = 97
print(float(variable_1))  #this prints 100.0
print(str(var2))  #this prints "10.220"
print(chr(var3))  #this prints "a"
var4 = float(variable_1)  #this prints 100.0
print(type(var4)) #this prints <class 'float'>
print(type(variable_1)) #this prints <class 'str'>